// Keyword brands & branded-model keyword data (client keyword research 2026-09).
// `matches` are normalized catalog model names (lowercase, non-alphanumerics stripped)
// that the entry applies to. Model names not covered fall back to template SEO.
// Brand entries are matched by their EXACT catalog brand string (see findBrandKeywords),
// so case-variant sibling brands (e.g. Deepal vs DEEPAL) never leak keywords.

export interface ModelKeywordEntry {
  primary: string
  secondaries: string[]
  /** normalized catalog model names this keyword covers (e.g. 'sealion07'). Empty = "source on request" only. */
  matches: string[]
}

export interface BrandKeywordEntry {
  /** exact catalog brand string, e.g. 'BYD' */
  brand: string
  primary: string
  secondaries: string[]
  models: ModelKeywordEntry[]
}

export function normModel(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '')
}

